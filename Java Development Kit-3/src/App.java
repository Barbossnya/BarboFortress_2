/* Урок 3. Обобщенное программирование
Создайте интерфейс, который определяет набор методов для работы с базой данных (например, сохранение, удаление, 
получение данных). Реализуйте этот интерфейс в конкретном классе.
*/
public class App {
    public static void main(String[] args) {
        DatabaseOperations db = new DatabaseManager();

        // Сохранение объектов
        db.save("Объект1");
        db.save("Объект2");

        // Получение объекта по ID
        System.out.println("Получение объекта с ID = 1: " + db.getById(1));

        // Обновление объекта
        db.update(1, "ОбновленныйОбъект1");

        // Повторное получение объекта
        System.out.println("Получение обновленного объекта с ID = 1: " + db.getById(1));

        // Удаление объекта
        db.delete(1);
        db.delete(3); // Пытаемся удалить объект с несуществующим ID
    }
}
